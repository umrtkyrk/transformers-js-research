def query(identifier, split, category, text, office, relevant, *, city=None,
          tenure=None, max_price=None, min_bedrooms=None):
    filters = {'active': True}
    for key, value in [('city', city), ('tenure', tenure),
                       ('max_price_gbp', max_price), ('min_bedrooms', min_bedrooms)]:
        if value is not None:
            filters[key] = value
    return dict(id=identifier, split=split, category=category, query=text,
                allowed_office=office, filters=filters, relevant_ids=relevant,
                expected_no_result=not relevant)


