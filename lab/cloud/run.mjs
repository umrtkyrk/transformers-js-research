import fs from 'node:fs/promises';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';

// Environment overrides must be set before importing the existing runner.
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
process.env.LAB_CONFIG_FILE=path.join(root,'lab/.state/cloud-config.json');
process.env.LAB_LOCAL_FILE=path.join(root,'lab/.state/cloud-local.json');
const {ROOT,STATE,readJSON,writeJSON,exists,state,saveState,settings,baseRequest,enqueue,executeRequest,withLock,scan,safeVersion}=await import('../core.mjs');
const {buildPublic,publicCopy}=await import('../report.mjs');
const repository=process.env.GITHUB_REPOSITORY??'umrtkyrk/transformers-js-research';
if(!/^[\w.-]+\/[\w.-]+$/.test(repository))throw new Error('Invalid repository');
const branch='results';
const store=path.join(root,'.cloud-results');
const runUrl='https://github.com/'+repository+'/actions/runs/'+process.env.GITHUB_RUN_ID;

function git(args,cwd=root,authenticated=false){return new Promise((resolve,reject)=>{
 const env={...process.env};
 if(authenticated){if(!env.GH_TOKEN)throw new Error('Workflow token is required');env.GIT_CONFIG_COUNT='1';env.GIT_CONFIG_KEY_0='http.https://github.com/.extraheader';env.GIT_CONFIG_VALUE_0='AUTHORIZATION: basic '+Buffer.from('x-access-token:'+env.GH_TOKEN).toString('base64');}
 const child=spawn('git',args,{cwd,env,windowsHide:true,stdio:['ignore','pipe','pipe']});let output='',error='';child.stdout.on('data',x=>output+=x);child.stderr.on('data',x=>error+=x);child.on('error',reject);child.on('exit',code=>code===0?resolve(output.trim()):reject(new Error('git '+args[0]+' failed: '+error.replace(/https:\/\/[^\s]+/g,'[repository]'))));
});}

async function restore(){
 await fs.mkdir(STATE,{recursive:true});
 const remote=await git(['ls-remote','https://github.com/'+repository+'.git','refs/heads/'+branch]);
 if(remote){
  await git(['clone','--depth','1','--single-branch','--branch',branch,'https://github.com/'+repository+'.git',store]);
  const saved=path.join(store,'cloud-state.json');if(await exists(saved))await fs.copyFile(saved,path.join(STATE,'state.json'));
  if(await exists(path.join(store,'lab')))await fs.cp(path.join(store,'lab'),path.join(root,'site/lab'),{recursive:true});
 }else{
  await fs.mkdir(store,{recursive:true});await git(['init','--initial-branch='+branch],store);await git(['remote','add','origin','https://github.com/'+repository+'.git'],store);
 }
 const config=await readJSON(path.join(ROOT,'config.json'));
 config.publish={...config.publish,enabled:false,pendingNativeLogin:false,staticDirectory:'../site'};
 config.execution={kind:'GitHub Actions',repository,runner:process.env.RUNNER_OS??process.platform,runnerImage:process.env.ImageOS??'windows-2025',runId:process.env.GITHUB_RUN_ID,runUrl};
 // A cold runner needs all five pinned model downloads, not just one new candidate.
 // Each later run keeps the ordinary per-update download limit.
 if(!(await exists(path.join(STATE,'assets'))))config.limits.maxDownloadBytesPerTick=3*1024**3;
 await writeJSON(process.env.LAB_CONFIG_FILE,config);
 const npmCli=process.env.NPM_CLI;if(!npmCli||!(await exists(npmCli)))throw new Error('NPM_CLI is missing');
 const edge=process.env.EDGE_PATH??'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
 if(!(await exists(edge)))throw new Error('Microsoft Edge is missing on this runner');
 await writeJSON(process.env.LAB_LOCAL_FILE,{npmCli,edgePath:edge,playwrightRoot:path.join(root,'.ci-tools/node_modules/playwright')});
}

async function checkpoint(s){
 await buildPublic(s);
 await fs.cp(path.join(root,'site/lab'),path.join(store,'lab'),{recursive:true});
 await writeJSON(path.join(store,'cloud-state.json'),publicCopy(s));
 await fs.writeFile(path.join(store,'README.md'),'# Recorded benchmark results\n\nGenerated by the research workflow. Model weights, credentials and private logs are excluded.\n');
 await git(['config','user.name','github-actions[bot]'],store);
 await git(['config','user.email','41898282+github-actions[bot]@users.noreply.github.com'],store);
 await git(['add','--','lab','cloud-state.json','README.md'],store);
 if(await git(['diff','--cached','--name-only'],store)){
  await git(['commit','-m','Record research run '+(process.env.GITHUB_RUN_ID??'local')],store);
  await git(['push','origin','HEAD:refs/heads/'+branch],store,true);
 }
}

await restore();
await withLock(async()=>{
 const s=await state();
 s.schedule={kind:'GitHub Actions',installed:true,dailyAt:null,taskName:'Research benchmarks',requiresComputerOn:false,repository};
 for(const item of s.queue)if(item.status==='running')item.status='interrupted';
 for(const row of s.runs)if(['running','preparing'].includes(row.status)){row.status='interrupted';row.completedAt=new Date().toISOString();row.error='Previous cloud workflow stopped before completion.';}
 const mode=process.env.LAB_MODE??'auto';if(!['auto','verify','scan'].includes(mode))throw new Error('Unknown mode');
 if(mode==='scan')await scan(s);
 else{
  const latest=await fetch('https://registry.npmjs.org/@huggingface%2ftransformers/latest',{signal:AbortSignal.timeout(30000)}).then(r=>{if(!r.ok)throw new Error('npm unavailable');return r.json()});
  safeVersion(latest.version);s.latestPackage=latest.version;
  const version=mode==='verify'?safeVersion(process.env.LAB_VERSION||'4.3.2'):latest.version;
  const {config}=await settings();if(Number(version.split('.')[0])!==config.watch.allowedMajor)throw new Error('New major release requires review');
  const request=await baseRequest(version,mode==='verify'?'cloud verification':'npm stable release');
  // Cloud verification intentionally establishes an independent host baseline.
  request.force=mode==='verify';enqueue(s,request);
  s.lastCheck={at:new Date().toISOString(),status:'completed',errors:[],queued:s.queue.filter(x=>x.status==='queued').length};
 }
 await saveState(s);await checkpoint(s);
 const pending=s.queue.find(x=>x.status==='queued');
 if(pending){
  const {config}=await settings();
  // Persist the queued state before expensive inference; failures still keep evidence.
  console.log(JSON.stringify({event:'cloud-job-start',version:pending.version,reason:pending.reason}));
  const result=await executeRequest(s,pending,{budget:{used:0,maximum:config.limits.maxDownloadBytesPerTick}});
  console.log(JSON.stringify({event:'cloud-job-finished',id:result.id,status:result.status,technical:result.summary?.technical}));
  if(result.status!=='completed')process.exitCode=1;
 }else console.log(JSON.stringify({event:'up-to-date',latest:s.latestPackage}));
 await checkpoint(s);
});
